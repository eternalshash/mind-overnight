#!/usr/bin/env python3
"""
generate_secrets.py — ECE 441 Smart HVAC Wi-Fi & MQTT Secrets Generator
========================================================================
Interactive tool to configure:
  1. Illinois Tech Campus IoT Network ('IIT-IoT' via https://iot.iit.edu)
  2. Cloud MQTT Broker (HiveMQ Cloud / EMQX over TLS port 8883)

Generates:
  arduino_secrets.h  (git-ignored header file for Arduino UNO R4 WiFi)
"""

import sys
import os
import argparse
import getpass

DEFAULT_SSID = "IIT-IoT"
DEFAULT_MQTT_PORT = 8883
HEADER_TEMPLATE = """#pragma once
// =============================================================================
// ECE 441: SMART HVAC CONTROL — ARDUINO UNO R4 WIFI SECRETS
// Auto-generated by generate_secrets.py
// DO NOT COMMIT THIS FILE TO VERSION CONTROL
// =============================================================================

// 1. Illinois Tech Campus Wi-Fi (Registered via https://iot.iit.edu)
#define SECRET_SSID "{ssid}"
#define SECRET_PASS "{wifi_pass}"

// 2. Cloud MQTT Broker (TLS / Secure Port 8883)
#define SECRET_BROKER "{broker_host}"
#define SECRET_PORT   {broker_port}
#define SECRET_USER   "{mqtt_user}"
#define SECRET_MQTT_PASS "{mqtt_pass}"

// 3. MQTT Topics
#define SECRET_TOPIC_TELEMETRY "ece441/group2/hvac/telemetry"
#define SECRET_TOPIC_COMMAND   "ece441/group2/hvac/command"
"""

def detect_serial_ports():
    ports = []
    try:
        import serial.tools.list_ports
        for p in serial.tools.list_ports.comports():
            ports.append(p.device)
    except ImportError:
        pass
    return ports

def print_banner():
    print("=" * 68)
    print("   ECE 441: Smart HVAC Control — Wireless & MQTT Setup Wizard")
    print("   Target Board: Arduino UNO R4 WiFi (ESP32-S3 Co-Processor)")
    print("=" * 68)

def print_iit_guide():
    print("""
---------------------------------------------------------------------
CAMPUS WI-FI REGISTRATION GUIDE (IIT-IoT)
---------------------------------------------------------------------
The Arduino UNO R4 WiFi cannot authenticate with IIT-Secure (802.1X).
To connect it to the official campus IoT network:

1. Flash the MAC address sketch to your Arduino UNO R4 WiFi.
2. Note your 6-byte MAC address (e.g., 34:B7:DA:12:34:56).
3. On your phone/laptop, go to:
     👉 https://iot.iit.edu
4. Sign in with your MyIIT portal credentials.
5. Click 'Register a Device':
     - Device Name: ECE441-HVAC-Arduino
     - MAC Address: <Your Arduino's MAC>
6. Copy the unique pre-shared WPA2 passphrase (PSK) generated by IIT OTS.
---------------------------------------------------------------------
""")

def run_wizard():
    print_banner()
    print_iit_guide()

    # Step 1: Wi-Fi
    ssid_in = input(f"Enter Wi-Fi SSID [{DEFAULT_SSID}]: ").strip()
    ssid = ssid_in if ssid_in else DEFAULT_SSID

    wifi_pass = input(f"Enter Passphrase (PSK from iot.iit.edu for '{ssid}'): ").strip()
    while not wifi_pass:
        print("  Passphrase cannot be empty for IIT-IoT.")
        wifi_pass = input(f"Enter Passphrase: ").strip()

    # Step 2: MQTT Broker
    print("\n--- Cloud MQTT Broker Configuration ---")
    print("Recommended: HiveMQ Cloud Free Serverless Cluster (https://www.hivemq.com/cloud/)")
    broker_host = input("Enter Cloud MQTT Broker Host (e.g. xxxxxx.s1.eu.hivemq.cloud): ").strip()
    while not broker_host:
        print("  Broker host is required.")
        broker_host = input("Enter Cloud MQTT Broker Host: ").strip()

    port_in = input(f"Enter MQTT TLS Port [{DEFAULT_MQTT_PORT}]: ").strip()
    port = int(port_in) if port_in else DEFAULT_MQTT_PORT

    mqtt_user = input("Enter MQTT Username: ").strip()
    mqtt_pass = getpass.getpass("Enter MQTT Password (hidden): ").strip()

    target_dirs = [
        os.path.dirname(os.path.abspath(__file__)),
        os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "HVAC-proto")),
        os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    ]

    header_content = HEADER_TEMPLATE.format(
        ssid=ssid,
        wifi_pass=wifi_pass,
        broker_host=broker_host,
        broker_port=port,
        mqtt_user=mqtt_user,
        mqtt_pass=mqtt_pass
    )

    written = []
    for d in target_dirs:
        if os.path.isdir(d):
            out_path = os.path.join(d, "arduino_secrets.h")
            with open(out_path, "w") as f:
                f.write(header_content)
            written.append(out_path)

    print("\n" + "=" * 68)
    print("SUCCESS: arduino_secrets.h generated!")
    for p in written:
        print(f"  -> {p}")
    print("=" * 68)
    print("Next step: Flash SmartHVAC_Arduino_Bench.ino to the Arduino UNO R4 WiFi.")
    print("The board will connect to IIT-IoT and stream telemetry to your broker.")
    print("=" * 68)

def main():
    parser = argparse.ArgumentParser(description="Generate arduino_secrets.h for ECE441 Smart HVAC")
    parser.add_argument("--ssid", default=None, help="Wi-Fi SSID (default: IIT-IoT)")
    parser.add_argument("--wifi-pass", default=None, help="Wi-Fi Passphrase")
    parser.add_argument("--broker", default=None, help="MQTT Broker Host")
    parser.add_argument("--port", type=int, default=DEFAULT_MQTT_PORT, help="MQTT Port (default: 8883)")
    parser.add_argument("--user", default=None, help="MQTT Username")
    parser.add_argument("--mqtt-pass", default=None, help="MQTT Password")
    args = parser.parse_args()

    if args.ssid and args.wifi_pass and args.broker:
        header_content = HEADER_TEMPLATE.format(
            ssid=args.ssid,
            wifi_pass=args.wifi_pass,
            broker_host=args.broker,
            broker_port=args.port,
            mqtt_user=args.user or "",
            mqtt_pass=args.mqtt_pass or ""
        )
        base_dir = os.path.dirname(os.path.abspath(__file__))
        out_path = os.path.join(base_dir, "arduino_secrets.h")
        with open(out_path, "w") as f:
            f.write(header_content)
        print(f"Wrote secrets to {out_path}")
    else:
        run_wizard()

if __name__ == "__main__":
    main()
